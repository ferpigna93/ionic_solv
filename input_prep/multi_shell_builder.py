#!/usr/bin/env python3
"""multi_shell_builder.py — Build multi-shell explicit water clusters for gas-phase DFT.

Strategy
--------
Convergence problems with the cluster-continuum (CC) model are avoided by
using a purely explicit solvent approach: all water molecules are included
explicitly and the calculation is run in gas phase (no SCRF/SMD).

Shell placement
~~~~~~~~~~~~~~~
Shell 1  (inner)  : Thomson-optimal O positions at radius R₁ from the ion.
                    O lone pairs face the cation (or H toward anion).
Shell 2+  (outer) : Each H of the previous shell is a H-bond donor.
                    The next shell's O is placed at distance d_HB along
                    the O–H bond direction, past the H:

                        inner_O ──── inner_H ··· outer_O
                                 R_OH            d_HB ≈ 1.80 Å

                    The outer water is oriented with its lone pairs toward
                    inner_H (i.e., it acts as H-bond acceptor).

                    If more waters are requested than available H-bond
                    sites (> 2 × n_prev), the excess is distributed via
                    Thomson on a sphere of radius R_prev + 2.76 Å.

Conformers
~~~~~~~~~~
Each conformer is generated by a single random global rotation of the
first shell, after which outer shells are recomputed from the new H
positions. This preserves Thomson geometry in shell 1 and H-bond
geometry in outer shells across all conformers.

Gas-phase only
~~~~~~~~~~~~~~
Only opt+freq gas-phase .com files are generated (no SCRF). The SCF
convergence difficulties associated with continuum models are therefore
avoided entirely.

Usage
-----
  # Na⁺ with 6-water inner shell + 12-water outer shell (18 waters total)
  python input_prep/multi_shell_builder.py \\
      -f examples/ions/Na.xyz -c 1 \\
      --shells 6 12 --nconformers 5 -o jobs/Na_explicit/

  # Three shells
  python input_prep/multi_shell_builder.py \\
      -f examples/ions/Na.xyz -c 1 \\
      --shells 6 12 18 --nconformers 3 -o jobs/Na_3shells/

  # Anion (H toward ion for shell 1)
  python input_prep/multi_shell_builder.py \\
      -f examples/ions/Cl.xyz -c -1 \\
      --shells 6 12 --anion --nconformers 5 -o jobs/Cl_explicit/
"""

